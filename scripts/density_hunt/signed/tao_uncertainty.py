#!/usr/bin/env python3
"""Tao uncertainty on Z/pZ applied to the signed Z(a).

Setup (prime q): identify (Z/q)* with F_q \\ {0}, or work on additive F_q with
the character Fourier transform on F_q.

Model: let f: F_q -> C with hat f supported on a set W of 'characters with a zero
in the box', |W| = M = q^{A(1-sigma)}. Tao (math/0308286): for nonzero f on Z/pZ,
  |supp f| + |supp hat f| >= p + 1.

If hat f = 1_W (or sparse on W), then |supp f| >= p+1-M.
That says f is NON-sparse on the a-side — the opposite of what we want for
pointwise smallness. Uncertainty prevents f from being concentrated on few a;
it does NOT force |f(a)| small for every a.

Quantitative Plancherel: sum_a |f(a)|^2 = q sum_{chi in W} |c_chi|^2.
If |c_chi|~1, then RMS = sqrt(M). Max could still be as large as M (all phases align
at one a) unless more structure.

Amplification attempt: for a multiplicative amplifier A subset (Z/q)* of size K,
sum_{b in A} |Z(ab)|^2. By expansion this is K * sum_chi |c_chi|^2 * |sum_{b in A} chi(b)|^2
/ something — standard DFI amplifier needs |sum_A chi| large for the bad chi and
small for others. Here W is defined by having zeros, not by a multiplicative
character condition, so there is no amplifier that preferentially detects W.

Verdict probe: print the uncertainty lower bound on |supp Z| and the Plancherel
RMS; confirm max can meet the triangle in a constructed example.
"""
from __future__ import annotations

import argparse
import numpy as np

A = 7 / 3
SIGMA = 5 / 7


def tao_bound(p: int, M: int) -> dict:
    # |supp f| >= p + 1 - M for hat-support size M
    return dict(p=p, M=M, supp_f_lower=max(p + 1 - M, 0),
                note="lower-bounds support size; does not upper-bound |f(a)|")


def constructed_spike(p: int, M: int, rng: np.random.Generator) -> dict:
    """hat f supported on M frequencies, phases chosen so f spikes at 0."""
    # Take hat f = 1 on a set W of size M; then f(a) = sum_{w in W} e^{2pi i w a / p}
    W = rng.choice(p, size=min(M, p), replace=False)
    a = np.arange(p)
    # f(a) = sum_w exp(2pi i w a / p)
    # Use FFT: place 1 at W
    hat = np.zeros(p, dtype=np.complex128)
    hat[W] = 1.0
    f = np.fft.ifft(hat) * p  # unnormalised: sum_w e^{...}
    absf = np.abs(f)
    return dict(
        max_abs=float(absf.max()),
        rms=float(np.sqrt(np.mean(absf ** 2))),
        triangle=float(len(W)),
        max_over_tri=float(absf.max() / max(len(W), 1)),
        n_near_max=int(np.sum(absf > 0.5 * absf.max())),
    )


def amplifier_identity(p: int, M: int, K: int, rng: np.random.Generator) -> dict:
    """sum_{b=1}^K |Z(a*g^b)|^2 for fixed a, random W — should be ~ K * M on average
    by Plancherel along the cyclic subgroup generated by g (primitive root).
    No pointwise saving for every a.
    """
    # work on (Z/p)* ~ Z/(p-1)
    n = p - 1
    W = rng.choice(n, size=min(M, n), replace=False)
    hat = np.zeros(n, dtype=np.complex128)
    hat[W] = 1.0
    Z = np.fft.fft(hat)  # length n
    # multiplicative shifts = cyclic shifts in the index domain after dlog
    # sum over K shifts of |Z|^2 equals K * ||Z||_2^2 / something? 
    # For cyclic shifts: sum_{k=0}^{K-1} |Z(j+k)|^2 averages to (K/n)*sum|Z|^2
    s = float(np.sum(np.abs(Z) ** 2))
    # worst a: max over starting points of sum of K consecutive |Z|^2
    abs2 = np.abs(Z) ** 2
    ker = np.ones(K)
    # circular
    ext = np.concatenate([abs2, abs2[: K - 1]])
    window = np.convolve(ext, ker, mode="valid")[:n]
    return dict(
        mean_window=float(np.mean(window)),
        max_window=float(np.max(window)),
        plancherel_K_M=K * M,  # if ||hat||_2^2 = M and FFT unitary-ish
        # numpy fft: sum|Z|^2 = n * sum|hat|^2
        sum_abs2=s,
        expected_mean=K * s / n,
    )


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--ps", type=int, nargs="+", default=[31, 61, 127, 251, 503])
    ap.add_argument("--seed", type=int, default=7)
    args = ap.parse_args()
    rng = np.random.default_rng(args.seed)
    print("Tao uncertainty + spike construction + amplifier windows")
    print(f"{'p':>6} {'M':>6} {'supp>=':>8} {'spike_max':>10} {'spike/tri':>10} "
          f"{'amp_max/mean':>12}")
    for p in args.ps:
        M = max(int(p ** (A * (1 - SIGMA))), 1)
        M = min(M, p - 1)
        tb = tao_bound(p, M)
        sp = constructed_spike(p, M, rng)
        K = max(M, 2)
        am = amplifier_identity(p, M, min(K, p - 1), rng)
        print(f"{p:6d} {M:6d} {tb['supp_f_lower']:8d} {sp['max_abs']:10.2f} "
              f"{sp['max_over_tri']:10.4f} "
              f"{am['max_window']/max(am['mean_window'],1e-300):12.3f}")
    print()
    print("Conclusion probe: spike_max/tri ~ 1 is achievable (aligned Fourier),")
    print("so uncertainty does NOT force pointwise saving. Amplifier windows")
    print("have max/mean = O(1) under random W — no every-a bound from L2.")


if __name__ == "__main__":
    main()
