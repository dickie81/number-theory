#!/usr/bin/env python3
"""fig_region.py [--check] [--table]: the figure of the region of the Type II estimate in two variables.

    python3 tools/linnik/fig_region.py            write papers/linnik-exponent/fig-region.tex
    python3 tools/linnik/fig_region.py --check    fail if the file on disk differs from what would be written
    python3 tools/linnik/fig_region.py --table    print the inequalities, the corners and the edges

The figure shows the region `R_L` of the paper's Definition `def:region` (Section 3.5, Proposition `prop:region`) in
the plane of `(m₁, m₂)`, where `P_i = q^{m_i}` are the lengths of the two variables: the region at `L = 43/20` as a
filled polygon with a solid outline, and its outline at `L = 21/10` dashed, with equal scales on the two axes. With
`s_i = 1 − m_i` and `ρ = L − m₁ − m₂` the region is

    ρ ≥ 1/2000,   m₁ ≥ 2/3,   m₂ ≥ 2/3,   s₁ + μ ≤ λρ,   s₂ + μ ≤ λρ,   s₁ + s₂ + μ ≤ λρ.

Each line of the region is a straight line in `(m₁, m₂)`, and the lines of `s₁ + μ ≤ λρ`, `s₂ + μ ≤ λρ`,
`s₁ + s₂ + μ ≤ λρ` and `ρ ≥ 1/2000` move outward as `L` grows, so the region at `21/10` lies inside the one at
`43/20` (the script checks it). The bound `m_i ≥ 2/3` does not touch the region at either exponent; the table says so.
The four inequalities that bound it are written beside their edges, the corners at `43/20` are marked with their
coordinates, and two thin gray lines mark `m₁ = 1` and `m₂ = 1` (a variable of length `q`, `s_i = 0`). Two corners
lie on these lines. The other two are the ends of the edge `ρ ≥ 1/2000`; they lie just off the lines (by `0.000141`),
too close to tell apart at this scale. The window of the axes is a view, fixed in the script (`XMIN` … `YMAX`); the
script checks that every corner lies inside it.

Where the numbers come from. The six inequalities are read from the definition `SieveTwoZone7D.Zone7d` in
`lib/pnt/SieveTwoZone7D.lean` (generated by `gen_zone.py`): the script parses each conjunct as a linear inequality
in `L`, `m₁`, `m₂` with exact rational coefficients, and checks that its constants are `gen_zone.py`'s `MU`, `LAM`,
`RHO0` and `MMIN`. The two exponents are read from the statements of `Linnik21500.linnik_21500` and
`Linnik21000.linnik_21000` (`lib/pnt/Linnik21500.lean`, `lib/pnt/Linnik21000.lean`). The corners are the vertices of
the polygon, found exactly with fractions: every pair of lines is intersected and the points that satisfy all six
inequalities are kept. Nothing in the figure is typed in by hand: the exponents in the legend and `1/2000` in the
edge label are written from the parsed values, and the TikZ rounds the exact corners to six decimals. The table prints
the corners exactly, with `ρ`, and the inequalities tight at each.

The one-variable remark at the end of Section 3 (`L ≥ 1 + A/2`) is a condition on `L` alone, not on `(m₁, m₂)`, so
the figure does not draw it.

`papers/linnik-exponent/fig-region.tex` is one `tikzpicture` (a `pgfplots` axis); `main.tex` puts it in a figure
with `\\input{fig-region}`. It needs `pgfplots` (`compat=1.16`) and the colours `figblue`, `figorange` and `figgray` of
the paper's preamble. Python 3, standard library only.
"""
import os
import re
import sys
from fractions import Fraction as Fr
from itertools import combinations

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, '..', '..')
PNT = os.path.join(ROOT, 'lib', 'pnt')
ZONE = os.path.join(PNT, 'SieveTwoZone7D.lean')
THEOREMS = {'21500': os.path.join(PNT, 'Linnik21500.lean'), '21000': os.path.join(PNT, 'Linnik21000.lean')}
OUT = os.path.join(ROOT, 'papers', 'linnik-exponent', 'fig-region.tex')

sys.path.insert(0, HERE)
import gen_zone  # noqa: E402  (the constants of the region, to check the parse against)

VARS = ('L', 'm₁', 'm₂')


# ---------------------------------------------------------------- reading the Lean

class Lin:
    """An affine form `c + Σ a_v v` in the variables `L`, `m₁`, `m₂`, with rational coefficients."""

    def __init__(self, c=Fr(0), **a):
        self.c = Fr(c)
        self.a = {v: Fr(a.get(v, 0)) for v in VARS}

    def __add__(self, o):
        r = Lin(self.c + o.c)
        r.a = {v: self.a[v] + o.a[v] for v in VARS}
        return r

    def __neg__(self):
        r = Lin(-self.c)
        r.a = {v: -self.a[v] for v in VARS}
        return r

    def __sub__(self, o):
        return self + (-o)

    def const(self):
        return all(x == 0 for x in self.a.values())

    def scale(self, k):
        r = Lin(self.c * k)
        r.a = {v: self.a[v] * k for v in VARS}
        return r


def parse_expr(s):
    """Parse a Lean real expression built from numerals, `L`, `m₁`, `m₂`, `+ − * /` and parentheses, as a `Lin`.
    A product or a quotient must have a constant factor (the region is linear)."""
    toks = re.findall(r'\d+|L|m₁|m₂|[-+*/()]', s)
    if ''.join(toks) != re.sub(r'\s+', '', s):
        raise SystemExit(f'fig_region: cannot parse {s!r}')
    pos = 0

    def peek():
        return toks[pos] if pos < len(toks) else None

    def take():
        nonlocal pos
        pos += 1
        return toks[pos - 1]

    def atom():
        t = take()
        if t == '(':
            e = expr()
            assert take() == ')'
            return e
        if t == '-':
            return -atom()
        if t in VARS:
            return _var(t)
        return Lin(int(t))

    def term():
        e = atom()
        while peek() in ('*', '/'):
            op, f = take(), atom()
            if op == '*':
                if f.const():
                    e = e.scale(f.c)
                elif e.const():
                    e = f.scale(e.c)
                else:
                    raise SystemExit(f'fig_region: a product of two variables in {s!r}')
            else:
                if not f.const():
                    raise SystemExit(f'fig_region: a division by a variable in {s!r}')
                e = e.scale(1 / f.c)
        return e

    def expr():
        e = term()
        while peek() in ('+', '-'):
            op, f = take(), term()
            e = e + f if op == '+' else e - f
        return e

    e = expr()
    if pos != len(toks):
        raise SystemExit(f'fig_region: trailing text in {s!r}')
    return e


def _var(v):
    r = Lin()
    r.a[v] = Fr(1)
    return r


def read_zone():
    """The six conjuncts of `Zone7d L m₁ m₂`, each as an affine form `f` with `f ≥ 0` (right side minus left)."""
    t = open(ZONE, encoding='utf-8').read()
    m = re.search(r'def Zone7d \(L m₁ m₂ : ℝ\) : Prop :=\n(.*?)\n\n', t, re.S)
    if not m:
        raise SystemExit('fig_region: no definition `Zone7d` in lib/pnt/SieveTwoZone7D.lean')
    parts = [p.strip() for p in m.group(1).split('∧')]
    out = []
    for p in parts:
        lhs, rhs = p.split('≤')
        out.append((p, parse_expr(rhs) - parse_expr(lhs)))
    if len(out) != 6:
        raise SystemExit(f'fig_region: `Zone7d` has {len(out)} conjuncts, not 6')
    return out


def read_exponent(path):
    """The exponent `L` in `p ≤ K * q ^ (a / b : ℝ)` of the main theorem of a file."""
    t = open(path, encoding='utf-8').read()
    m = re.search(r'theorem linnik_\d+ :.*?\(q : ℝ\) \^ \((\d+) / (\d+) : ℝ\)', t, re.S)
    if not m:
        raise SystemExit(f'fig_region: no exponent in {os.path.relpath(path, ROOT)}')
    return Fr(int(m.group(1)), int(m.group(2)))


# ---------------------------------------------------------------- the paper's names of the inequalities

def name(f):
    """The inequality `f ≥ 0` in the paper's notation, recognised from its coefficients (`s_i = 1 − m_i`,
    `ρ = L − m₁ − m₂`): `ρ ≥ ρ₀`, `m_i ≥ c`, or `Σ s_i + μ ≤ λρ` over a set of the `s_i`."""
    a1, a2, aL, c = f.a['m₁'], f.a['m₂'], f.a['L'], f.c
    if aL == 1 and a1 == a2 == -1:
        return ('rho', -c)
    if aL == 0 and (a1, a2) in ((1, 0), (0, 1)):
        return ('m1' if a1 else 'm2', -c)
    # λ(L − m₁ − m₂) − Σ_{i∈I} (1 − m_i) − μ, so a_i = 1 − λ for i ∈ I and −λ otherwise
    lam = aL
    I = tuple(i for i, a in ((1, a1), (2, a2)) if a == 1 - lam)
    if all(a in (1 - lam, -lam) for a in (a1, a2)) and I:
        mu = -c - len(I)
        return ('s' + ''.join(map(str, I)), lam, mu)
    raise SystemExit(f'fig_region: an inequality of `Zone7d` not of the expected shape: {f.a}, {c}')


def check_constants(zone):
    names = [name(f) for _, f in zone]
    kinds = sorted(n[0] for n in names)
    if kinds != ['m1', 'm2', 'rho', 's1', 's12', 's2']:
        raise SystemExit(f'fig_region: unexpected inequalities in `Zone7d`: {kinds}')
    for n in names:
        if n[0] == 'rho':
            assert n[1] == gen_zone.RHO0, n
        elif n[0] in ('m1', 'm2'):
            assert n[1] == gen_zone.MMIN, n
        else:
            assert (n[1], n[2]) == (gen_zone.LAM, gen_zone.MU), n
    return names


TEX = {
    'rho': r'$\rho \ge {rho0}$',     # {rho0}: the constant parsed from the Lean
    's1': r'$s_1 + \mu \le \lambda\rho$',
    's2': r'$s_2 + \mu \le \lambda\rho$',
    's12': r'$s_1 + s_2 + \mu \le \lambda\rho$',
    'm1': r'$m_1 \ge 2/3$',
    'm2': r'$m_2 \ge 2/3$',
}


# ---------------------------------------------------------------- the polygon

def at(f, L):
    """The form `f` at the exponent `L`: `(a₁, a₂, c)` with the inequality `a₁m₁ + a₂m₂ + c ≥ 0`."""
    return f.a['m₁'], f.a['m₂'], f.c + f.a['L'] * L


def polygon(zone, L):
    """The vertices of the region at `L`, exactly, in counter-clockwise order, each with the inequalities tight
    there; and the inequalities that bound an edge."""
    lines = [(k, at(f, L)) for k, (_, f) in enumerate(zone)]
    pts = {}
    for (i, (a1, a2, c)), (j, (b1, b2, d)) in combinations(lines, 2):
        det = a1 * b2 - a2 * b1
        if det == 0:
            continue
        x = (-c * b2 + d * a2) / det
        y = (-a1 * d + b1 * c) / det
        if all(e1 * x + e2 * y + e >= 0 for _, (e1, e2, e) in lines):
            pts[(x, y)] = None
    if len(pts) < 3:
        raise SystemExit(f'fig_region: the region at L = {L} is not a polygon')
    cx = sum(p[0] for p in pts) / len(pts)
    cy = sum(p[1] for p in pts) / len(pts)
    import math
    order = sorted(pts, key=lambda p: math.atan2(float(p[1] - cy), float(p[0] - cx)))
    verts = []
    for x, y in order:
        tight = [k for k, (e1, e2, e) in lines if e1 * x + e2 * y + e == 0]
        verts.append((x, y, tight))
    edges = []
    for u, v in zip(verts, verts[1:] + verts[:1]):
        common = sorted(set(u[2]) & set(v[2]))
        if len(common) != 1:
            raise SystemExit(f'fig_region: an edge at L = {L} lies on {len(common)} lines')
        edges.append((common[0], u, v))
    return verts, edges


def data():
    zone = read_zone()
    names = check_constants(zone)
    Ls = {tag: read_exponent(p) for tag, p in THEOREMS.items()}
    polys = {tag: polygon(zone, L) for tag, L in Ls.items()}
    return zone, names, Ls, polys


def lit(x):
    return f'{x.numerator}' if x.denominator == 1 else f'{x.numerator}/{x.denominator}'


def table():
    zone, names, Ls, polys = data()
    print('Zone7d (lib/pnt/SieveTwoZone7D.lean), each conjunct with its name in the paper:')
    for (src, _), n in zip(zone, names):
        print(f'  {src:60s}  {n[0]:4s} ' + ' '.join(lit(x) for x in n[1:]))
    for tag, L in Ls.items():
        verts, edges = polys[tag]
        print(f'\nL = {lit(L)} = {float(L)} (linnik_{tag}): {len(verts)} corners')
        for x, y, tight in verts:
            rho = L - x - y
            print(f'  (m₁, m₂) = ({float(x):.6f}, {float(y):.6f})  ρ = {float(rho):.6f} = {lit(rho)}  '
                  f'tight: {", ".join(names[k][0] for k in tight)}')
            print(f'      exactly ({lit(x)}, {lit(y)})')
        print('  edges on: ' + ', '.join(names[k][0] for k, _, _ in edges))
        unused = [names[k][0] for k in range(6) if k not in {e[0] for e in edges}]
        print('  inequalities that touch no edge: ' + ', '.join(unused))


# ---------------------------------------------------------------- the TikZ

def f6(x):
    s = f'{float(x):.6f}'.rstrip('0').rstrip('.')
    return s


def pt(x, y):
    return f'({f6(x)},{f6(y)})'


# The window of the axes (a view, not data): it holds the region at the larger exponent and the corners' labels.
XMIN, XMAX, YMIN, YMAX = Fr(72, 100), Fr(134, 100), Fr(82, 100), Fr(12, 10)
TICKS = (Fr(8, 10), Fr(9, 10), Fr(1), Fr(11, 10), Fr(12, 10), Fr(13, 10))
THM = {'21500': 'thm:4320', '21000': 'thm:2110'}     # the labels of the two theorems in main.tex


def legend(tag, L):
    return r'$\mathcal R_{' + lit(L) + r'}$, Theorem~\ref{' + THM[tag] + '}'


def tex():
    zone, names, Ls, polys = data()
    hi, lo = '21500', '21000'
    for tag in (hi, lo):
        for x, y, _ in polys[tag][0]:
            assert XMIN < x < XMAX and YMIN < y < YMAX, (tag, x, y)    # nothing clipped
    vh, eh = polys[hi]
    vl, _ = polys[lo]
    for x, y, _ in vl:                        # the region at the smaller L lies inside the one at the larger
        assert all(f.a['m₁'] * x + f.a['m₂'] * y + f.a['L'] * Ls[hi] + f.c >= 0 for _, f in zone), (x, y)
    kind = {k: names[k][0] for k in range(6)}
    rho0 = next(n[1] for n in names if n[0] == 'rho')

    def label(k):
        return TEX[kind[k]].replace('{rho0}', lit(rho0))
    cx = sum(x for x, _, _ in vh) / len(vh)
    cy = sum(y for _, y, _ in vh) / len(vh)

    def cs(x, y):
        return f'(axis cs:{f6(x)},{f6(y)})'

    def cyc(vs):
        return ' '.join(pt(x, y) for x, y, _ in vs + vs[:1])

    ticks = ','.join(f6(t) for t in TICKS if XMIN <= t <= XMAX)
    yticks = ','.join(f6(t) for t in TICKS if YMIN <= t <= YMAX)
    out = []
    w = out.append
    w('% Generated by tools/linnik/fig_region.py; do not edit by hand.')
    w(f'% The region R_L of Definition def:region (SieveTwoZone7D.Zone7d) in the plane (m_1, m_2): at L = {lit(Ls[hi])}')
    w(f'% filled with a solid outline, at L = {lit(Ls[lo])} dashed. Corners rounded to six decimals from the exact values.')
    w(r'\begin{tikzpicture}')
    w(r'\begin{axis}[')
    w(r'  width=11.6cm, height=8cm, axis equal image,')
    w(f'  xmin={f6(XMIN)}, xmax={f6(XMAX)}, ymin={f6(YMIN)}, ymax={f6(YMAX)},')
    w(f'  xtick={{{ticks}}}, ytick={{{yticks}}},')
    w(r'  tick style={figgray, line width=0.4pt}, major tick length=3pt, tick align=outside, xtick pos=left, ytick pos=left,')
    w(r'  tick label style={font=\footnotesize}, /pgf/number format/.cd, fixed, precision=1,')
    w(r'  /pgfplots/.cd, axis line style={figgray, line width=0.4pt},')
    w(r'  xlabel={$m_1$}, ylabel={$m_2$}, label style={font=\small}, ylabel style={rotate=-90},')
    w(r'  legend style={font=\footnotesize, draw=none, fill=none, at={(0.98,0.97)}, anchor=north east,')
    w(r'    row sep=1pt}, legend cell align=left,')
    w(r'  clip=false,')
    w(r']')
    w('% guides: the variables of length q (s_1 = 0 and s_2 = 0)')
    w(r'\addplot[figgray, line width=0.3pt, forget plot] coordinates {' + pt(1, YMIN) + ' ' + pt(1, YMAX) + '};')
    w(r'\addplot[figgray, line width=0.3pt, forget plot] coordinates {' + pt(XMIN, 1) + ' ' + pt(XMAX, 1) + '};')
    w(f'% the region at L = {lit(Ls[hi])}')
    w(r'\addplot[figblue, line width=0.9pt, fill=figblue, fill opacity=0.12, draw opacity=1] coordinates {' +
      cyc(vh) + '};')
    w(r'\addlegendentry{' + legend(hi, Ls[hi]) + '}')
    w(f'% the region at L = {lit(Ls[lo])}')
    w(r'\addplot[figorange, line width=0.9pt, dash pattern=on 3pt off 2pt] coordinates {' + cyc(vl) + '};')
    w(r'\addlegendentry{' + legend(lo, Ls[lo]) + '}')
    w('% the inequalities, each beside its edge at the larger L, outside the region')
    for k, u, v in eh:
        if (u[0], u[1]) > (v[0], v[1]):
            u, v = v, u                       # left to right, so that `above` is above the line
        # the centre lies below the line through u, v exactly when the cross product is negative
        side = 'above' if (v[0] - u[0]) * (cy - u[1]) - (v[1] - u[1]) * (cx - u[0]) < 0 else 'below'
        w(r'\path ' + cs(u[0], u[1]) + ' -- ' + cs(v[0], v[1]) +
          f' node[midway, sloped, {side}, font=\\footnotesize, inner sep=2.5pt] {{{label(k)}}};')
    w('% the corners at the larger L, with their coordinates')
    for x, y, _ in vh:
        dx, dy = x - cx, y - cy
        if abs(dx) > abs(dy):
            anchor = 'south east' if dx < 0 else 'south west'
        else:
            anchor = 'south east' if dy > 0 else 'north west'    # beside the guide m_1 = 1, not across it
        w(r'\fill ' + cs(x, y) + r' circle[radius=1.3pt] node[anchor=' + anchor + r', font=\footnotesize, inner sep=2.5pt] {$(' +
          f6(x) + ', ' + f6(y) + ')$};')
    w(r'\end{axis}')
    w(r'\end{tikzpicture}')
    return '\n'.join(out) + '\n'


def main():
    if '--table' in sys.argv:
        table()
        return
    t = tex()
    rel = os.path.relpath(OUT, ROOT)
    if '--check' in sys.argv:
        cur = open(OUT, encoding='utf-8').read() if os.path.exists(OUT) else ''
        if cur != t:
            raise SystemExit(f'fig_region: {rel} differs from the generated text')
        print(f'fig_region: {rel} up to date')
        return
    with open(OUT, 'w', encoding='utf-8') as f:
        f.write(t)
    print(f'fig_region: wrote {rel}')


if __name__ == '__main__':
    main()
