#!/usr/bin/env python3
"""Tables from the output of Census.lean.

    python3 scratch/axiomless/census_report.py OUT.tsv [--area-depth N] [--weights FILE]

Prints, for the theorems of the census that a person wrote: how many depend on each set of axioms; how many are
free of axioms, have a statement free of axioms but a proof that is not, or have a statement that already rests on
axioms; each axiom's share of proofs and of statements; the three classes by area of the library; and the
constants that name an axiom themselves.

A theorem that a person wrote is one whose name is not internal or private and that Lean did not generate: the
lemmas `injEq`, `inj`, `sizeOf_spec`, `congr_simp`, `eq_def`, `eq_1`, `induct` and the like, which come with every
inductive type and definition, are counted apart.

With `--weights FILE` it writes one line for each constant, `1` for a theorem that a person wrote and `0`
otherwise: the weights that gateways.c counts.
"""
import re
import sys
from collections import Counter, defaultdict

GENERATED = re.compile(r"^(injEq|inj|sizeOf_spec|congr_simp|eq_def|eq_\d+|induct|induct_unfolding|fun_cases|"
                       r"fun_cases_unfolding|congr_eq_\d+|eq_unfold|ctorIdx.*|noConfusion.*|brecOn.*|below.*|splitter|"
                       r"ctorElim.*|mutual_induct|rec_\d+|binductionOn.*|hinj|elim)$")

def generated(name):
    """Whether Lean generated the constant with an inductive type, a definition or a match."""
    return bool(GENERATED.match(name.split(".")[-1]) or re.search(r"\.match_\d+\.", name))

def written(r):
    """A theorem with a name a person wrote, not generated by Lean."""
    return r[1] == "theorem" and not r[7] and not generated(r[0])

def load(path):
    axioms, rows = {}, []
    with open(path, encoding="utf-8") as f:
        for line in f:
            p = line.rstrip("\n").split("\t")
            if p[0] == "#axiom":
                axioms[int(p[1])] = p[2]
            else:
                rows.append((p[0], p[1], p[2], int(p[3]), int(p[4]), int(p[5]), int(p[6]), p[7] == "1"))
    return axioms, rows

def names(mask, axioms):
    out = [axioms[k] for k in sorted(axioms) if mask >> k & 1]
    return " + ".join(out) if out else "(none)"

def area(module, depth):
    return ".".join(module.split(".")[:depth])

def main():
    args = sys.argv[1:]
    depth, weights = 2, None
    if "--area-depth" in args:
        i = args.index("--area-depth"); depth = int(args[i + 1]); del args[i:i + 2]
    if "--weights" in args:
        i = args.index("--weights"); weights = args[i + 1]; del args[i:i + 2]
    axioms, rows = load(args[0])
    if weights:
        with open(weights, "w") as f:
            f.write("".join("1\n" if written(r) else "0\n" for r in rows))
    kinds = Counter(r[1] for r in rows)
    print(f"{len(rows)} constants: " + ", ".join(f"{v} {k}" for k, v in kinds.most_common()))
    named = [r for r in rows if r[1] == "theorem" and not r[7]]
    gen = [r for r in named if generated(r[0])]
    print(f"{len(named)} theorems with a name that is not internal or private; Lean generated {len(gen)} of them, "
          f"{sum(1 for r in gen if r[3] == 0)} free of axioms")
    ie = [r for r in gen if r[0].endswith(".injEq")]
    print(f"  among them {len(ie)} lemmas injEq, {sum(1 for r in ie if r[3] == 0)} free of axioms")
    thms = [r for r in rows if written(r)]
    n = len(thms)
    print(f"\n== theorems that a person wrote: {n}")
    for mask, v in Counter(r[3] for r in thms).most_common(8):
        print(f"  {v:8d}  {100 * v / n:5.1f}%  {names(mask, axioms)}")
    free = [r for r in thms if r[3] == 0]
    proof_only = [r for r in thms if r[3] != 0 and r[4] == 0]
    stmt = [r for r in thms if r[4] != 0]
    print("\n== three classes")
    print(f"  free of axioms:                           {len(free):8d}  {100 * len(free) / n:5.1f}%")
    print(f"  statement free, proof uses axioms:        {len(proof_only):8d}  {100 * len(proof_only) / n:5.1f}%")
    print(f"  statement rests on axioms:                {len(stmt):8d}  {100 * len(stmt) / n:5.1f}%")
    print("\n== each axiom: in the proof or the statement, in the statement")
    for k in sorted(axioms):
        full = sum(1 for r in thms if r[3] >> k & 1)
        st = sum(1 for r in thms if r[4] >> k & 1)
        if full:
            print(f"  {axioms[k]:18s} {full:8d} {100 * full / n:5.1f}%   {st:8d} {100 * st / n:5.1f}%")
    print(f"\n== by area (depth {depth}): theorems, % free, % statement free only, % statement on axioms")
    by = defaultdict(lambda: [0, 0, 0])
    for r in thms:
        a = by[area(r[2], depth)]
        a[0 if r[3] == 0 else 1 if r[4] == 0 else 2] += 1
    for a, (x, y, z) in sorted(by.items(), key=lambda kv: -sum(kv[1])):
        t = x + y + z
        if t >= 200:
            print(f"  {a:40s} {t:7d}  {100 * x / t:5.1f}  {100 * y / t:5.1f}  {100 * z / t:5.1f}")
    print("\n== constants that name an axiom themselves")
    for k in sorted(axioms):
        users = [r for r in rows if r[5] >> k & 1]
        if users:
            simp = sum(1 for r in users if re.search(r"\._simp_\d+", r[0]))
            print(f"  {axioms[k]}: {len(users)} constants ({simp} of them auxiliary lemmas of simp)")
    nat = [r for r in thms if r[0].startswith("Nat.")]
    print(f"\n== namespace Nat: {len(nat)} theorems, {sum(1 for r in nat if r[3] == 0)} free of axioms")

if __name__ == "__main__":
    main()
